// @ts-check
import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { existsSync, readFileSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";

/**
 * Password-protected case studies (`protected: true`), server side. See DECISIONS.md.
 *
 * Astro builds two pages for each one: the full case study at /work/<slug> and the locked state at
 * /work/<slug>/locked. After the build this integration moves the full page out of `dist` into a
 * generated module (.generated/protected-pages.js) and puts the locked page in its place. The only
 * copy of the content is then inside the Pages Function (functions/work/_middleware.ts), which
 * serves it after the password is entered. Nothing in `dist` can leak it.
 */

const WORK_DIR = new URL("../src/content/work/", import.meta.url);
const MODULE = new URL("../.generated/protected-pages.js", import.meta.url);

/** Slugs of case studies marked `protected: true` in their frontmatter. */
export function protectedSlugs() {
  return readdirSync(WORK_DIR, { withFileTypes: true })
    .filter((dir) => dir.isDirectory())
    .map((dir) => dir.name)
    .filter((slug) => {
      const file = new URL(`${slug}/index.mdx`, WORK_DIR);
      if (!existsSync(file)) return false;
      const frontmatter = readFileSync(file, "utf8").split(/^---\s*$/m)[1] ?? "";
      return /^protected:\s*true\s*$/m.test(frontmatter);
    });
}

/** @returns {import("astro").AstroIntegration} */
export default function protectedWork() {
  return {
    name: "protected-work",
    hooks: {
      "astro:build:done": async ({ dir, logger }) => {
        const work = new URL("work/", dir);
        /** @type {Record<string, string>} */
        const pages = {};
        const dirs = existsSync(work) ? await readdir(work, { withFileTypes: true }) : [];
        for (const entry of dirs.filter((d) => d.isDirectory())) {
          const slug = entry.name;
          const locked = new URL(`${slug}/locked.html`, work);
          const full = new URL(`${slug}.html`, work);
          if (!existsSync(locked)) continue;
          if (existsSync(full)) pages[slug] = await readFile(full, "utf8");
          await writeFile(full, await readFile(locked));
          await rm(new URL(`${slug}/`, work), { recursive: true });
        }
        await mkdir(new URL(".", MODULE), { recursive: true });
        await writeFile(
          MODULE,
          `// Generated by tooling/protected-work.mjs on build. Do not edit or commit.\nexport default ${JSON.stringify(pages)};\n`,
        );
        const slugs = Object.keys(pages);
        logger.info(
          slugs.length
            ? `Locked ${slugs.join(", ")}; content moved to ${fileURLToPath(MODULE)}`
            : "No protected case studies",
        );
      },
    },
  };
}
